    // The gap this closes. Before it, `GrpcDispatcher`'s
    // success arm was hardcoded to `finish(bytes, RpcStatus::ok())` -- a
    // handler returning `Ok(R)` had no channel for response metadata at
    // all, so a SUCCESSFUL call could never set a header or a trailer
    // (only a FAILED one could, via `RpcStatus::with_trailer`). This
    // handler succeeds and sets both; the dispatcher must surface both as
    // reserved headers on the 200 response, the exact same encoding the
    // error arm already uses (`HEADER_PREFIX`/`TRAILER_PREFIX`), which is
    // what lets the host convert them identically regardless of which arm
    // produced them.
    fn echo_with_metadata(_req: &mut Req<'_>, msg: TestMsg) -> Result<Response<TestMsg>, RpcStatus> {
        Ok(Response::new(msg)
            .with_header("x-request-id", "req-42")
            .with_trailer("x-server-timing", "7ms"))
    }

    #[test]
    fn a_successful_call_can_set_a_response_header_and_a_trailer() {
        let d = GrpcDispatcher::new("test.EchoService").method("Echo", echo_with_metadata);
        let body = TestMsg { text: "hi".to_string() }.encode_to_vec();
        let request = test_req("/test.EchoService/Echo", vec![], body);
        let params = crate::router::Params::from_pairs(vec![]);
        let mut req = Req { request: &request, params: &params, ctx: crate::ctx::Ctx::new() };
        let resp = d.handle(&mut req);

        assert!(
            resp.headers.contains(&(STATUS_HEADER.to_string(), "0".to_string())),
            "a successful call must still carry OK status; got {:?}",
            resp.headers
        );
        assert!(
            resp.headers.contains(&(
                format!("{HEADER_PREFIX}x-request-id"),
                "req-42".to_string()
            )),
            "expected the response header to survive dispatch; got {:?}",
            resp.headers
        );
        assert!(
            resp.headers.contains(&(
                format!("{TRAILER_PREFIX}x-server-timing"),
                "7ms".to_string()
            )),
            "expected the trailer to survive dispatch on the SUCCESS arm; got {:?}",
            resp.headers
        );
    }


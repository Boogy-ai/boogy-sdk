    // A minimal hand-written `Message` impl for exercising `GrpcDispatcher`
    // without a generated proto crate — that codegen is a build-time
    // toolchain (protox + connectrpc-build) that isn't wired into
    // boogy-sdk's own build, so there is no generated message type
    // available here. The binary codec below is a deliberate no-op stub —
    // same shape as buffa's own `__doctest_fixtures::Person` — so it
    // proves nothing about wire-format correctness (that's buffa's job,
    // and the codegen's own for the generated types); it exists only to
    // exercise `GrpcDispatcher::handle`'s routing/dispatch/status-header
    // machinery. The JSON side, by contrast, uses a real `serde` derive,
    // so `handle_dispatches_the_json_codec_and_round_trips_the_field`
    // genuinely proves the field value survives the codec.
    #[derive(Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]
    struct TestMsg {
        text: String,
    }

    impl buffa::DefaultInstance for TestMsg {
        fn default_instance() -> &'static Self {
            static INST: std::sync::OnceLock<TestMsg> = std::sync::OnceLock::new();
            INST.get_or_init(TestMsg::default)
        }
    }

    impl buffa::Message for TestMsg {
        fn compute_size(&self, _cache: &mut buffa::SizeCache) -> u32 {
            0
        }
        fn write_to(&self, _cache: &mut buffa::SizeCache, _buf: &mut impl buffa::EncodeSink) {}
        fn merge_field(
            &mut self,
            tag: buffa::encoding::Tag,
            buf: &mut impl buffa::bytes::Buf,
            _ctx: buffa::DecodeContext<'_>,
        ) -> Result<(), buffa::DecodeError> {
            buffa::encoding::skip_field(tag, buf)
        }
        fn clear(&mut self) {
            *self = Self::default();
        }
    }

    fn echo(_req: &mut Req<'_>, msg: TestMsg) -> Result<Response<TestMsg>, RpcStatus> {
        Ok(msg.into())
    }

